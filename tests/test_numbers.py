"""numbers.tex generated from results/: traceable and valid LaTeX macro names.

Every number the paper prints is one of these macros, read from a results/ run.
"""

from __future__ import annotations

import re


def test_numbers_have_macros(numbers_tex: str) -> None:
    assert re.findall(r"\\newcommand\{\\([A-Za-z]+)\}", numbers_tex), \
        "numbers.tex has no macros; run scripts/make_numbers.py"


def test_numbers_have_a_traceability_comment(numbers_tex: str) -> None:
    assert "AUTOGENERATED by scripts/make_numbers.py" in numbers_tex
    assert "results/" in numbers_tex


def test_macro_names_are_alphabetic(numbers_tex: str) -> None:
    # LaTeX control words cannot contain digits; a stray digit would only fail at
    # build time.
    names = re.findall(r"\\newcommand\{\\([^}]+)\}", numbers_tex)
    assert names
    bad = [n for n in names if not n.isalpha()]
    assert not bad, f"non-alphabetic macro names in numbers.tex: {bad}"
