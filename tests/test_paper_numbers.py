"""The manuscript may only use numeric macros defined in paper/numbers.tex.

AGENTS.md rule 1: every number in the paper comes from results/.  This guards
against a macro being referenced in main.tex without a corresponding generated
definition (which would surface as an "Undefined control sequence" only at build
time).
"""

from __future__ import annotations

import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
PAPER = REPO_ROOT / "paper"


def _defined_macros() -> set[str]:
    text = (PAPER / "numbers.tex").read_text()
    return set(re.findall(r"\\newcommand\{\\([A-Za-z]+)\}", text))


def test_every_number_macro_used_is_defined():
    defined = _defined_macros()
    assert defined, "numbers.tex has no macros; run scripts/make_numbers.py"
    used = set(re.findall(r"\\([A-Z][A-Za-z]+)", (PAPER / "main.tex").read_text()))
    latex_builtins = {
        "LaTeX", "IEEEPARstart", "IEEEtran", "IEEEkeywords", "IEEEpeerreviewmaketitle",
        "DocumentMetadata", "TeX", "S", "T", "Delta",
    }
    missing = used - defined - latex_builtins
    assert not missing, f"main.tex uses undefined macros: {sorted(missing)}"


def test_numbers_have_a_traceability_comment():
    text = (PAPER / "numbers.tex").read_text()
    assert "AUTOGENERATED by scripts/make_numbers.py" in text
    assert "results/" in text
