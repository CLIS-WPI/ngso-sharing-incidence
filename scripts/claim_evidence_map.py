"""Claim-evidence map for paper/main.tex (numbers.tex macros -> results/ runs).

Writes ``paper/claim_evidence_map.md`` with

1. every ``paper/main.tex`` line that prints a ``numbers.tex`` macro: the macro, its
   value and the ``results/`` run it was read from (``% Name <- results/...`` in
   numbers.tex), and whether that run directory exists;
2. macros used in the text with no results/ source (constants written by
   ``scripts/make_numbers.py`` from code or config);
3. literal numbers typed in the body text (not macros), for manual review;
4. the heuristic claim list of the ai-research-writing skill's ``extract_claims.py``
   if its output is passed with ``--skill-claims``.

Usage:  python scripts/claim_evidence_map.py [--skill-claims FILE]
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
MAIN = REPO / "paper" / "main.tex"
NUMBERS = REPO / "paper" / "numbers.tex"
OUT = REPO / "paper" / "claim_evidence_map.md"

LATEX_WORDS = {"S", "Delta", "Pr", "Gamma", "Theta", "Phi", "Psi", "Omega", "Sigma", "Lambda",
               "IEEEauthorblockN", "IEEEauthorblockA", "IEEEauthorrefmark",
               "IEEEoverridecommandlockouts", "IEEEtran", "IEEEkeywords", "IEEEPARstart"}
MATH_ENVS = ("equation", "align", "eqnarray", "multline", "gather")
MACRO_USE = re.compile(r"\\([A-Z][A-Za-z]+)(?![A-Za-z])")
# Commands whose arguments are not prose numbers.
STRIP = [re.compile(p) for p in (
    r"(?<!\\)%.*$",                            # comments (not an escaped \%)
    r"\\(cite|ref|label|eqref|url|href|includegraphics|input|bibliography\w*|"
    r"documentclass|usepackage|setlength|renewcommand|newcommand|rowcolors|"
    r"definecolor|multicolumn|begin|end|hspace|vspace|columnwidth)\*?"
    r"(\[[^\]]*\])*(\{[^{}]*\})*",
    r"\\S\\?,?\s*25\.\d+(\([a-z0-9]\))*",      # rule sections
    r"\\[A-Za-z]+",                            # remaining control words (macros)
    r"\$[^$]*\$",                              # inline math
)]
NUM = re.compile(r"(?<![A-Za-z])\d+(?:[.,]\d+)*(?![A-Za-z]*\})")


def read_numbers() -> tuple[dict[str, str], dict[str, str]]:
    txt = NUMBERS.read_text(encoding="utf-8")
    val = dict(re.findall(r"\\newcommand\{\\([A-Za-z]+)\}\{([^}]*)\}", txt))
    src = dict(re.findall(r"^% ([A-Za-z]+) <- results/([^/\s]+)/", txt, flags=re.M))
    return val, src


def md(rows: list[dict]) -> str:
    if not rows:
        return "(none)"
    cols = list(rows[0])
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(r[c]).replace("|", "\\|") for c in cols) + " |" for r in rows]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--skill-claims", type=Path, default=None)
    args = ap.parse_args()
    val, src = read_numbers()
    lines = MAIN.read_text(encoding="utf-8").splitlines()
    abstract = next(i for i, s in enumerate(lines) if "\\begin{abstract}" in s) + 1
    in_math = in_ack = False
    traced, constants, missing, literal = [], {}, [], []
    for n, line in enumerate(lines, 1):
        body = re.sub(r"(?<!\\)%.*$", "", line)
        used = [m for m in MACRO_USE.findall(body) if m in val]
        unknown = [m for m in MACRO_USE.findall(body) if m not in val and m not in LATEX_WORDS]
        for m in used:
            if m in src:
                run = src[m]
                traced.append({"line": n, "macro": m, "value": val[m], "run": f"results/{run}/",
                               "run exists": "yes" if (REPO / "results" / run).is_dir() else "**NO**"})
            else:
                constants.setdefault(m, {"macro": m, "value": val[m], "lines": []})["lines"].append(n)
        for m in unknown:
            missing.append({"line": n, "macro": m})
        if any(f"\\begin{{{e}" in line for e in MATH_ENVS):
            in_math = True
        if line.strip().startswith("\\section*{Acknowledgment"):
            in_ack = True
        if n > abstract and not in_math and not in_ack:
            t = body
            for pat in STRIP:
                t = pat.sub(" ", t)
            nums = [x for x in NUM.findall(t)]
            if nums:
                literal.append({"line": n, "numbers": ", ".join(nums),
                                "text": line.strip()[:120]})
        if any(f"\\end{{{e}" in line for e in MATH_ENVS):
            in_math = False
    L = ["# Claim-evidence map: paper/main.tex", "",
         "Generated by `scripts/claim_evidence_map.py`; do not edit by hand.  Every printed "
         "result in the text is a `paper/numbers.tex` macro written by "
         "`scripts/make_numbers.py` from the run named here.", "",
         f"## 1. Result macros in the text ({len(traced)} uses, "
         f"{len({r['macro'] for r in traced})} macros)", "", md(traced), "",
         f"## 2. Macros without a results/ source ({len(constants)}): rule constants, config "
         "values or fixed text written by make_numbers.py", "",
         md([{**c, "lines": ", ".join(map(str, c["lines"]))} for c in constants.values()]), "",
         f"## 3. Capitalised control words in the text that are not numbers.tex macros "
         f"({len(missing)})", "", md(missing), "",
         f"## 4. Literal numbers in the body text ({len(literal)} lines), for manual review", "",
         "Numbers typed directly in `main.tex` from the abstract to the acknowledgment (rule "
         "section numbers, display and inline math, and macro arguments removed).  Each is either a definition (rule, standard, filing, date), a "
         "model setting, or a result that should be a macro.", "", md(literal), ""]
    if args.skill_claims and args.skill_claims.exists():
        L += ["## 5. Heuristic claim list (ai-research-writing-skill `extract_claims.py`)", "",
              args.skill_claims.read_text(encoding="utf-8"), ""]
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    n_bad = sum(r["run exists"] != "yes" for r in traced)
    print(f"wrote {OUT}: {len(traced)} traced uses ({n_bad} with a missing run), "
          f"{len(constants)} source-less macros, {len(missing)} unknown control words, "
          f"{len(literal)} lines with literal numbers")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
